package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"

	"git.happydns.org/happyDomain/services/abstract"
)

func main() {
	output := flag.String("o", "", "output file path")
	flag.Parse()

	if *output == "" {
		fmt.Fprintf(os.Stderr, "Error: output file path is required\n")
		fmt.Fprintf(os.Stderr, "Usage: %s -o <output-file>\n", os.Args[0])
		os.Exit(1)
	}

	fd, err := os.Create(*output)
	if err != nil {
		panic(err)
	}
	defer fd.Close()

	providers, err := json.MarshalIndent(abstract.VerificationProviders, "", "    ")
	if err != nil {
		panic(err)
	}

	fmt.Fprint(fd, "// This file is generated by go generate\n\n")

	fmt.Fprintln(fd, `export interface VerificationProvider {
    name: string;
    label?: string;
    prefix?: string;
}`)

	fmt.Fprintf(fd, "\n// The first provider matching a record wins, as in services/abstract/domain-verification.go.\nexport const verificationProviders: VerificationProvider[] = %s;\n", string(providers))

	fmt.Printf("Generated %s with %d verification providers\n", *output, len(abstract.VerificationProviders))
}
